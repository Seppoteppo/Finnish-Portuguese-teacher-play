  <p>Nämä neljä verbiä ovat tärkeitä ja yleisiä. Ne ovat <b>epäsäännöllisiä</b>, eli taivutus ei seuraa tavallista mallia. Epäsäännöllisyys on lähes aina vain minä-muodossa (<span class="pt">eu</span>). Muut muodot ovat tuttuja.</p>
